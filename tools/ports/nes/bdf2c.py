# bdf2c.py FONT.bdf OUT.h: the printable ASCII glyphs (32-126) of a fixed
# 8-pixel-wide BDF font (misc-fixed 8x13: public domain) as a C array,
# font[95][13], one byte per row, for nes's game menu.
import sys
src, out = sys.argv[1], sys.argv[2]
height = 13
glyphs = {}
code = None
rows = None
bbx = None
ascent = 11
for line in open(src, encoding="latin-1"):
    w = line.split()
    if not w:
        continue
    if w[0] == "FONT_ASCENT":
        ascent = int(w[1])
    elif w[0] == "ENCODING":
        code = int(w[1])
    elif w[0] == "BBX":
        bbx = [int(x) for x in w[1:5]]
    elif w[0] == "BITMAP":
        rows = []
    elif w[0] == "ENDCHAR":
        if code is not None and 32 <= code <= 126 and rows is not None:
            cell = [0] * height
            bw, bh, bx, by = bbx
            top = ascent - (by + bh)  # first row in the cell
            for i, r in enumerate(rows):
                y = top + i
                if 0 <= y < height:
                    cell[y] = (int(r, 16) >> max(0, len(r) * 4 - 8)) >> bx if bx >= 0 else int(r, 16)
            glyphs[code] = cell
        code = rows = None
    elif rows is not None:
        rows.append(w[0])
with open(out, "w") as f:
    f.write("/* Generated by bdf2c.py from misc-fixed 8x13 (public domain). */\n")
    f.write("static const unsigned char font[95][%d] = {\n" % height)
    for c in range(32, 127):
        cell = glyphs.get(c, [0] * height)
        f.write("    {" + ", ".join("0x%02x" % (b & 0xff) for b in cell) + "}, /* %r */\n" % chr(c))
    f.write("};\n")
